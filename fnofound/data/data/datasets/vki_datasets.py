"""
vki_datasets.py - dataset loaders for the VKI-LS59 experiments.

Two cases, one common interface (the same sample dict as airfoil_datasets):

    SquareDataset    ('square') - DNO_dataset npy on the universal square
                                  128x128 (generated by prep_square.py)
    RawGridDataset   ('raw')    - original PLAID structured C-grid 301x121
                                  (needs the `plaid` package + square_dev)

Each sample is a dict:
    x         : [H, W, 5]   input channels: (x, y, sdf) + scalar conditions
                             (angle_in, mach_out) broadcast as constant
                             channels (so the models need no scalar head)
    y         : [H, W, 6]   output fields: mach, nut, ro, roe, rou, rov
    mask      : None        (no holes: the whole grid is fluid)
    grid_mesh : [H, W, 2]   physical (x, y) - DNO geometry terms (also set
                             for raw, for a uniform interface)
    pos       : None

Splits (defined by the dataset itself, not by index ranges):
    train: train_500 (500 samples), val: the other 171 of train,
    test: 168 samples WITHOUT outputs (only inputs, as in the HF dataset).

Data (external drive, not committed):
    square: {root_dir}/DNO_dataset   (train_inputs.npy, ..., meta.json)
    raw:    {plaid_dir}              (original PLAID dataset + split.json)
"""

import json
import os
from typing import List, Optional

import numpy as np
import torch
from torch.utils.data import Dataset

from fnofound.data.data.datasets.airfoil_datasets import collate_fn

OUT_FIELDS = ('mach', 'nut', 'ro', 'roe', 'rou', 'rov')
IN_FIELDS = ('x', 'y', 'sdf')
SCALAR_FIELDS = ('angle_in', 'mach_out')


# ═══════════════ universal square 128x128 (DNO / RNO_D) ═══════════════

class SquareDataset(Dataset):
    """Universal square from DNO_dataset (npy, channel-last [N, H, W, C]).

    Splits come from meta.json: train = train_500_ids (500), val = the rest
    of train_ids (171), test = test_inputs.npy (168, no outputs).
    """

    def __init__(self, root_dir: str, split: str = 'train',
                 indices: Optional[List[int]] = None, want_y: bool = True):
        self.meta = json.load(open(os.path.join(root_dir, 'meta.json')))
        self.split = split
        self.want_y = want_y

        x = np.load(os.path.join(root_dir, 'train_inputs.npy'))       # [Ntr, H, W, 3]
        scal = np.load(os.path.join(root_dir, 'train_scalars.npy'))   # [Ntr, 2]
        train_ids = np.array(self.meta['train_ids'])

        if indices is not None:
            sel = np.where(np.isin(train_ids, [int(i) for i in indices]))[0]
            self.ids = train_ids[sel]
        elif split == 'test':
            x = np.load(os.path.join(root_dir, 'test_inputs.npy'))
            scal = np.load(os.path.join(root_dir, 'test_scalars.npy'))
            sel = np.arange(len(x))
            self.ids = np.array(self.meta.get('test_ids', sel))
        elif split == 'train':
            sel = np.where(np.isin(train_ids, self.meta['train_500_ids']))[0]
            self.ids = train_ids[sel]
        elif split == 'val':
            sel = np.where(~np.isin(train_ids, self.meta['train_500_ids']))[0]
            self.ids = train_ids[sel]
        else:
            raise ValueError(f'split={split!r} (train|val|test)')

        self.x = x[sel]
        self.scal = scal[sel]
        self.y = None
        if want_y:
            self.y = np.load(os.path.join(root_dir, 'train_outputs.npy'))[sel]
        self.H, self.W = self.x.shape[1], self.x.shape[2]
        self.global_ids = [int(i) for i in self.ids]

    def __len__(self):
        return len(self.x)

    def __getitem__(self, i):
        x = self.x[i]                                   # [H, W, 3] (x, y, sdf)
        s = self.scal[i]                                # [2]
        xin = np.concatenate([
            x,
            np.broadcast_to(s[None, None, :], (self.H, self.W, 2)),
        ], axis=-1).astype(np.float32)                  # [H, W, 5]
        y = torch.from_numpy(self.y[i]) if self.y is not None else None
        return {
            'x': torch.from_numpy(xin),
            'y': y,
            'mask': None,
            'grid_mesh': torch.from_numpy(x[..., :2].astype(np.float32)),
            'pos': None,
        }


# ═══════════════ raw structured C-grid 301x121 (FNO / RNO) ═══════════════

def _mesh_topology(s, base):
    """(i,j)-rectangle of the structured mesh: (ij_to_node [ni, nj], quads).

    Topology is constant across the dataset -> compute once, reuse.
    """
    from fnofound.utils.square_dev import boundary_loop, split_sides, structured_ij

    nodes = s.get_nodes(base_name=base)
    els = s.get_elements(base_name=base)
    quads = els[list(els.keys())[0]]
    tags = s.get_nodal_tags(base_name=base)
    tag_of = {}
    for tname, ids in tags.items():
        for i in ids:
            tag_of.setdefault(int(i), []).append(tname)

    n = len(nodes)
    loop = boundary_loop(quads, n)
    sides = split_sides(loop, tag_of)
    ij, _ = structured_ij(nodes, quads, sides, loop)

    ni = int(ij[:, 0].max()) + 1
    nj = int(ij[:, 1].max()) + 1
    assert ij.shape[0] == n and (ij >= 0).all(), 'not all nodes got (i,j)'
    assert ni * nj == n, f'ni*nj={ni*nj} != n={n} - (i,j) not a bijection'

    ij_to_node = np.full((ni, nj), -1, dtype=np.int64)
    for k in range(n):
        i, j = ij[k]
        assert ij_to_node[i, j] == -1, f'(i,j)=({i},{j}) taken twice'
        ij_to_node[i, j] = k
    return ij_to_node, quads


class RawGridDataset(Dataset):
    """Raw structured C-grid [H, W] = [301, 121] (Base_2_2) from plaid.

    Nodes are arranged into the (i,j)-rectangle by ij_to_node (constant
    topology). Requires the `plaid` package (only for this case).
    """

    def __init__(self, plaid_dir: str, split: str = 'train',
                 indices: Optional[List[int]] = None, want_y: bool = True,
                 preload: bool = True, clamp: bool = True, base: str = 'Base_2_2'):
        try:
            from plaid.containers.dataset import Dataset
        except ImportError as e:
            raise ImportError(
                'RawGridDataset needs the `plaid` package '
                '(pip install plaid-lib); the square case does not need it.'
            ) from e

        self.ds = Dataset.load_from_dir(plaid_dir, verbose=False)
        split_json = json.load(open(os.path.join(plaid_dir, 'split.json')))
        train_ids = list(split_json['train'])
        train_500 = list(split_json['train_500'])

        if indices is not None:
            ids = [int(i) for i in indices]
        elif split == 'test':
            ids = list(split_json['test'])
        elif split == 'train':
            ids = train_500
        elif split == 'val':
            ids = [i for i in train_ids if i not in set(train_500)]
        else:
            raise ValueError(f'split={split!r} (train|val|test)')

        self.ids = ids
        self.want_y = want_y
        self.base = base
        self.fields = list(OUT_FIELDS)
        self.clamp = clamp
        self.global_ids = [int(i) for i in ids]

        s0 = self.ds[self.ids[0]]
        self.ij_to_node, self.quads0 = _mesh_topology(s0, base)
        self.H, self.W = self.ij_to_node.shape          # 301 x 121

        if preload:
            self._preload()
        else:
            self._cache = None

    def _preload(self):
        n = len(self.ids)
        X = np.empty((n, self.H, self.W, 3), dtype=np.float32)
        Y = np.empty((n, self.H, self.W, 6), dtype=np.float32) if self.want_y else None
        S = np.empty((n, 2), dtype=np.float32)
        ij = self.ij_to_node
        for k, sid in enumerate(self.ids):
            s = self.ds[sid]
            els = s.get_elements(base_name=self.base)
            quads = els[list(els.keys())[0]]
            assert np.array_equal(quads, self.quads0), \
                f'topology of sample {sid} differs from the first one'
            nodes = np.asarray(s.get_nodes(base_name=self.base))
            sdf = np.asarray(s.get_field('sdf', base_name=self.base)).astype(np.float64)
            if self.clamp:
                sdf = np.maximum(sdf, 0.0)
            X[k] = np.stack([nodes[:, 0][ij], nodes[:, 1][ij], sdf[ij]], axis=-1)
            if self.want_y:
                outs = [np.asarray(s.get_field(f, base_name=self.base)).astype(np.float64)
                        for f in self.fields]
                if self.clamp:
                    outs[self.fields.index('nut')] = np.maximum(outs[self.fields.index('nut')], 0.0)
                Y[k] = np.stack([o[ij] for o in outs], axis=-1)
            S[k] = [float(s.get_scalar('angle_in')), float(s.get_scalar('mach_out'))]
        self._cache = (X, Y, S)
        print(f'RawGridDataset: {n} samples, grid {self.H}x{self.W}, '
              f'in {X.shape[1:]}, out {Y.shape[1:] if Y is not None else None}')

    def __len__(self):
        return len(self.ids)

    def __getitem__(self, i):
        if self._cache is not None:
            X, Y, S = self._cache
            x = X[i]
            y = Y[i] if Y is not None else None
            scal = S[i]
        else:
            s = self.ds[self.ids[i]]
            ij = self.ij_to_node
            nodes = np.asarray(s.get_nodes(base_name=self.base))
            sdf = np.asarray(s.get_field('sdf', base_name=self.base)).astype(np.float64)
            if self.clamp:
                sdf = np.maximum(sdf, 0.0)
            x = np.stack([nodes[:, 0][ij], nodes[:, 1][ij], sdf[ij]], -1)
            y = None
            if self.want_y:
                outs = [np.asarray(s.get_field(f, base_name=self.base)).astype(np.float64)
                        for f in self.fields]
                if self.clamp:
                    outs[self.fields.index('nut')] = np.maximum(outs[self.fields.index('nut')], 0.0)
                y = np.stack([o[ij] for o in outs], -1)
            scal = np.array([float(s.get_scalar('angle_in')),
                             float(s.get_scalar('mach_out'))], dtype=np.float32)

        xin = np.concatenate([
            x,
            np.broadcast_to(scal[None, None, :], (self.H, self.W, 2)),
        ], axis=-1).astype(np.float32)                  # [H, W, 5]
        return {
            'x': torch.from_numpy(xin),
            'y': torch.from_numpy(y) if y is not None else None,
            'mask': None,
            'grid_mesh': torch.from_numpy(x[..., :2].astype(np.float32)),
            'pos': None,
        }


# ═══════════════ factory ═══════════════

def get_vki_dataset(case: str, root_dir: str, plaid_dir: Optional[str] = None,
                    split: str = 'train', indices: Optional[List[int]] = None,
                    want_y: bool = True, cache: bool = False):
    """
    Build a dataset for the given case and split.

    case : 'square' | 'raw'
        square: DNO_dataset npy (DNO / RNO_D on the 128x128 square);
        raw:    original PLAID C-grid 301x121 (FNO / RNO).
    root_dir : str
        Root with the case data (square: {root_dir}/DNO_dataset).
    plaid_dir : str or None
        PLAID dataset dir (required for the raw case).
    split : 'train' | 'val' | 'test'
        train = train_500 (500), val = the other 171, test = 168 (no y).
    indices : list[int] or None
        Exact sample ids (takes precedence over split).
    want_y : bool
        False for the test split (no outputs there).
    cache : bool
        Preload all data into RAM (raw case).
    """
    if case == 'square':
        return SquareDataset(os.path.join(root_dir, 'DNO_dataset'),
                             split=split, indices=indices, want_y=want_y)
    if case == 'raw':
        if plaid_dir is None:
            raise ValueError('raw case needs plaid_dir')
        return RawGridDataset(plaid_dir, split=split, indices=indices,
                              want_y=want_y, preload=cache)
    raise ValueError(f'unknown case: {case}')
